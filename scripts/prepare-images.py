#!/usr/bin/env python3
"""Prepare story illustrations for the BuildHybridAI storybook scaffold.

Sources (all already generated by the Little Red Riding Hood project):
  - gemini-K*.jpeg : 9:16 keyframes (some 1536x2752, some 768x1376)
  - frames/S*.webp : 3:2 landscape frames for the 6 keyframes with no file
    in keyframes/ (K01/K03/K07/K13/K23/K29); center-cropped to 9:16.

Output: public/images/*.jpg, 9:16, max 768px wide, JPEG q80-82.
"""
import os
from PIL import Image

SRC = os.path.expanduser(
    "~/workspace/little-red-riding-hood-walkthrough-20261114/storyboard-v5-echo"
)
OUT = os.path.expanduser(
    "~/workspace/buildhybridai/little-red-ai-storybook/public/images"
)
os.makedirs(OUT, exist_ok=True)

# (source file, output name, kind)  kind: 'v' = vertical 9:16 already, 'crop' = 3:2 -> 9:16 center crop
JOBS = [
    ("frames/S01.webp", "cottage.jpg", "crop"),       # K01 cover: red-roof cottage
    ("keyframes/gemini-K02.jpeg", "kitchen.jpg", "v"),  # K02 table: basket + mum + Red
    ("frames/S06.webp", "gate.jpg", "crop"),          # K03 gate: hunter at the fence
    ("keyframes/gemini-K05.jpeg", "flowers.jpg", "v"),  # K05 daisy field
    ("keyframes/gemini-K04.jpeg", "road.jpg", "v"),     # K04 village road
    ("frames/S16.webp", "wolf.jpg", "crop"),          # K07 wolf + Red at the big tree
    ("keyframes/gemini-K12.jpeg", "fork.jpg", "v"),     # K12 fork in the road + map
    ("frames/S30A.webp", "bridge.jpg", "crop"),       # K13 bridge + footprints
    ("keyframes/gemini-K11.jpeg", "wolf-bed.jpg", "v"),  # K11 wolf in nightcap under blanket
    ("keyframes/gemini-K19.jpeg", "door.jpg", "v"),     # K19 threshold: bulging blanket
    ("keyframes/gemini-K22.jpeg", "bed.jpg", "v"),      # K22 wolf in bed, mid-shot
    ("frames/S48B.webp", "glasses.jpg", "crop"),      # K23 glasses tangled in nightcap
    ("keyframes/gemini-K24.jpeg", "reveal.jpg", "v"),   # K24 reveal: ears up, tail out
    ("keyframes/gemini-K25.jpeg", "help.jpg", "v"),     # K25 hunter + Red at the gate
    ("keyframes/gemini-K26.jpeg", "walk.jpg", "v"),     # K26 walking the stone path
    ("frames/S68.webp", "reunion.jpg", "crop"),       # K29 grandma holds Red's hand
    ("keyframes/gemini-K31.jpeg", "basket.jpg", "v"),   # K31 basket + cake on the table
    ("keyframes/gemini-K32.jpeg", "cake.jpg", "v"),     # K32 grandma smells the cake
    ("keyframes/gemini-K34.jpeg", "finale.jpg", "v"),   # K34 reunion tableau
]


def process(src_path, out_path, kind):
    im = Image.open(src_path).convert("RGB")
    if kind == "crop":
        # center-crop 3:2 landscape to 9:16 portrait
        w, h = im.size
        target_w = int(h * 9 / 16)
        left = (w - target_w) // 2
        im = im.crop((left, 0, left + target_w, h))
    # downscale to max 768 wide
    if im.width > 768:
        im = im.resize((768, int(im.height * 768 / im.width)), Image.LANCZOS)
    im.save(out_path, "JPEG", quality=80, optimize=True)
    return os.path.getsize(out_path)


total = 0
for src, name, kind in JOBS:
    src_path = os.path.join(SRC, src)
    out_path = os.path.join(OUT, name)
    size = process(src_path, out_path, kind)
    total += size
    print(f"{name:14s} {size // 1024:4d} KB  <- {src}")

print(f"TOTAL: {total // 1024} KB, {len(JOBS)} images")
